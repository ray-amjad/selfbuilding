import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, sep } from "node:path";
import { skillInvalid } from "./errors.js";
import { loadSkillRegistry } from "./registry.js";
import type { LoadOptions, SkillDef, SkillSource } from "./types.js";

export const GENERATED_HEADER = "// generated by `selfbuilding skills build`, do not edit";
const HASHES_PREFIX = "// selfbuilding-skill-hashes: ";

/** kebab-case to PascalCase: "improve-codebase-architecture" → "ImproveCodebaseArchitecture". */
export function exportName(skillName: string): string {
  return skillName
    .split("-")
    .filter((p) => p.length > 0)
    .map((p) => p[0]?.toUpperCase() + p.slice(1))
    .join("");
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Maps each skill to its export name; a collision or an invalid identifier is an error (spec §2.5.2). */
export function exportNames(skills: readonly Pick<SkillDef, "name" | "dir">[]): Map<string, string> {
  const byExport = new Map<string, string>();
  const out = new Map<string, string>();
  const issues: string[] = [];
  for (const s of skills) {
    const name = exportName(s.name);
    if (!IDENTIFIER.test(name)) {
      issues.push(`skill "${s.name}" converts to "${name}", which is not a valid identifier; rename the skill`);
      continue;
    }
    const prior = byExport.get(name);
    if (prior) {
      issues.push(`skills "${prior}" and "${s.name}" both convert to "${name}"; rename one`);
      continue;
    }
    byExport.set(name, s.name);
    out.set(s.name, name);
  }
  if (issues.length > 0) throw skillInvalid(skills.map((s) => s.dir).join(", "), issues);
  return out;
}

function importPath(fromFile: string, target: string, trailingSlash = false): string {
  let rel = relative(dirname(fromFile), target).split(sep).join("/");
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return trailingSlash && !rel.endsWith("/") ? `${rel}/` : rel;
}

type JsonSchema = Record<string, unknown>;

/** A small JSON Schema → TypeScript type printer for metadata contracts (spec §2.5.2). Unknown shapes become `unknown`. */
export function jsonSchemaToTs(schema: unknown, indent = ""): string {
  if (schema === true || schema === undefined) return "unknown";
  if (schema === false) return "never";
  if (schema === null || typeof schema !== "object") return "unknown";
  const s = schema as JsonSchema;
  if ("const" in s) return JSON.stringify(s.const);
  if (Array.isArray(s.enum)) return s.enum.map((v) => JSON.stringify(v)).join(" | ") || "never";
  for (const key of ["anyOf", "oneOf"] as const) {
    const variants = s[key];
    if (Array.isArray(variants)) return variants.map((v) => wrap(jsonSchemaToTs(v, indent))).join(" | ") || "never";
  }
  if (Array.isArray(s.allOf)) return s.allOf.map((v) => wrap(jsonSchemaToTs(v, indent))).join(" & ") || "unknown";
  if (Array.isArray(s.type)) {
    return s.type.map((t) => wrap(jsonSchemaToTs({ ...s, type: t }, indent))).join(" | ");
  }
  switch (s.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      if (Array.isArray(s.items)) return `[${s.items.map((i) => jsonSchemaToTs(i, indent)).join(", ")}]`;
      return `${wrap(jsonSchemaToTs(s.items, indent))}[]`;
    case "object":
      return objectType(s, indent);
    default:
      return s.properties ? objectType(s, indent) : "unknown";
  }
}

function wrap(t: string): string {
  return /[|&]/.test(t) && !/^[{[]/.test(t) ? `(${t})` : t;
}

function objectType(s: JsonSchema, indent: string): string {
  const props = (s.properties ?? {}) as Record<string, unknown>;
  const required = new Set(Array.isArray(s.required) ? (s.required as string[]) : []);
  const inner = `${indent}  `;
  const lines = Object.entries(props).map(([key, value]) => {
    const name = IDENTIFIER.test(key) ? key : JSON.stringify(key);
    return `${inner}${name}${required.has(key) ? "" : "?"}: ${jsonSchemaToTs(value, inner)};`;
  });
  const extra = s.additionalProperties;
  if (extra && typeof extra === "object") lines.push(`${inner}[key: string]: ${jsonSchemaToTs(extra, inner)};`);
  else if (extra === true || (extra === undefined && lines.length === 0)) lines.push(`${inner}[key: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

export interface GenerateOptions {
  /** Absolute path of the file being generated; imports are relative to it. */
  outFile: string;
  /** Default "@selfbuilding/core". */
  coreImport?: string;
}

/** Source text of `selfbuilding/skills.gen.ts` for the given skills (spec §2.5.2). */
export function generateSkillsModule(skills: readonly SkillDef[], opts: GenerateOptions): string {
  const sorted = [...skills].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const names = exportNames(sorted);
  const header = [
    GENERATED_HEADER,
    `${HASHES_PREFIX}${sorted.map((s) => `${s.name}=${s.hash}`).join(",")}`,
    `import { Agent } from "${opts.coreImport ?? "@selfbuilding/core"}";`,
  ];
  const imports: string[] = [];
  const body: string[] = [];
  for (const s of sorted) {
    const name = names.get(s.name) as string;
    const url = `new URL("${importPath(opts.outFile, s.dir, true)}", import.meta.url)`;
    const contractKind = s.contract === "inherited" ? s.inheritedFrom?.contract : s.contract;
    body.push("");
    if (s.sidecarPath && (contractKind === "sidecar" || s.contract === "sidecar")) {
      const local = `${name[0]?.toLowerCase()}${name.slice(1)}Contract`;
      imports.push(`import ${local} from "${importPath(opts.outFile, s.sidecarPath)}";`);
      body.push(`export const ${name} = await Agent.fromSkill(${url}, ${local});`);
    } else if (contractKind === "metadata" && s.jsonSchemas) {
      body.push(`export type ${name}Input = ${jsonSchemaToTs(s.jsonSchemas.input)};`);
      body.push(`export type ${name}Result = ${jsonSchemaToTs(s.jsonSchemas.output)};`);
      body.push(`export const ${name} = await Agent.fromSkill<${name}Input, ${name}Result>(${url});`);
    } else {
      body.push(`export const ${name} = await Agent.fromSkill(${url});`);
    }
  }
  return `${[...header, ...imports, ...body].join("\n")}\n`;
}

/** The skill hashes recorded in a generated file's header, by name. */
export function readGeneratedHashes(source: string): Map<string, string> | null {
  const line = source.split("\n").find((l) => l.startsWith(HASHES_PREFIX));
  if (line === undefined) return null;
  const out = new Map<string, string>();
  for (const pair of line.slice(HASHES_PREFIX.length).split(",")) {
    const at = pair.indexOf("=");
    if (at > 0) out.set(pair.slice(0, at), pair.slice(at + 1));
  }
  return out;
}

/** Compares a generated file with the skills as they are now (`selfbuilding skills check`). */
export function checkSkillsModule(source: string, skills: readonly SkillDef[]): { stale: boolean; reasons: string[] } {
  const recorded = readGeneratedHashes(source);
  if (!recorded)
    return { stale: true, reasons: ["the file has no skill-hash header; run `selfbuilding skills build`"] };
  const reasons: string[] = [];
  const current = new Map(skills.map((s) => [s.name, s.hash]));
  for (const [name, hash] of current) {
    const was = recorded.get(name);
    if (was === undefined) reasons.push(`skill ${name} is new`);
    else if (was !== hash) reasons.push(`skill ${name} changed`);
  }
  for (const name of recorded.keys()) if (!current.has(name)) reasons.push(`skill ${name} was removed`);
  return { stale: reasons.length > 0, reasons };
}

export interface BuildSkillsOptions extends LoadOptions, GenerateOptions {
  sources: SkillSource[];
}

/** Loads the sources and writes the generated module. Returns what was written. */
export async function buildSkills(
  opts: BuildSkillsOptions,
): Promise<{ outFile: string; skills: SkillDef[]; source: string }> {
  const registry = await loadSkillRegistry(opts.sources, { ...opts, importSidecar: false });
  const skills = registry.list();
  const source = generateSkillsModule(skills, opts);
  await mkdir(dirname(opts.outFile), { recursive: true });
  await writeFile(opts.outFile, source);
  return { outFile: opts.outFile, skills, source };
}

/** Reads the generated module and reports whether it is stale. A missing file is stale. */
export async function checkSkills(opts: BuildSkillsOptions): Promise<{ stale: boolean; reasons: string[] }> {
  const registry = await loadSkillRegistry(opts.sources, { ...opts, importSidecar: false });
  const source = await readFile(opts.outFile, "utf8").catch(() => null);
  if (source === null)
    return { stale: true, reasons: [`${opts.outFile} does not exist; run \`selfbuilding skills build\``] };
  return checkSkillsModule(source, registry.list());
}
